//! Command-line entry point for local platform CI.

use std::process::ExitCode;

fn main() -> ExitCode {
    match qubit_infra_platform::run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("error: {error:#}");
            ExitCode::FAILURE
        }
    }
}
